def search_github(query: str, max_results: int = 3) -> list:
    results = []
    try:
        encoded_q = urllib.parse.quote_plus(query)
        url = f"https://api.github.com/search/repositories?q={encoded_q}&sort=stars&order=desc&per_page={max_results}"
        req = urllib.request.Request(url, headers={"User-Agent": "FalconAutonomousResearcher/2.0"})
        with urllib.request.urlopen(req, timeout=8) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            for item in data.get("items", []):
                results.append({
                    "type": "github_repo",
                    "title": item.get("full_name", ""),
                    "url": item.get("html_url", ""),
                    "snippet": item.get("description", "") or "No description",
                    "stars": item.get("stargazers_count", 0)
                })
    except Exception as e:
        print(f"[-] GitHub search error for '{query}': {e}")
    return results

def search_crossref(query: str, max_results: int = 3) -> list:
    results = []
    try:
        encoded_q = urllib.parse.quote_plus(query)
        url = f"https://api.crossref.org/works?query={encoded_q}&rows={max_results}"
        req = urllib.request.Request(url, headers={"User-Agent": "FalconAutonomousResearcher/2.0 (mailto:research@example.com)"})
        with urllib.request.urlopen(req, timeout=8) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            items = data.get("message", {}).get("items", [])
            for item in items:
                titles = item.get("title", [])
                title = titles[0] if titles else "Untitled Paper"
                doi = item.get("DOI", "")
                url = f"https://doi.org/{doi}" if doi else ""
                container = item.get("container-title", ["Academic Journal"])[0] if item.get("container-title") else "Journal"
                results.append({
                    "type": "academic_paper",
                    "title": title,
                    "url": url,
                    "snippet": f"Published in {container}. Subject: {', '.join(item.get('subject', []))[:100]}"
                })
    except Exception as e:
        print(f"[-] CrossRef search error for '{query}': {e}")
    return results

