class LiveThoughtStreamer(TextStreamer):
    def __init__(self, tokenizer, on_token_cb, **kwargs):
        super().__init__(tokenizer, **kwargs)
        self.on_token_cb = on_token_cb
        self.accumulated = ""
        self.last_update = 0.0

    def on_finalized_text(self, text: str, stream_end: bool = False):
        self.accumulated += text
        now = time.time()
        if now - self.last_update > 0.8 or stream_end:
            self.last_update = now
            if self.on_token_cb:
                self.on_token_cb(self.accumulated, stream_end)

